using LuxMap.Persistence.Conventions;
using LuxMap.Shared.Authorization;
using LuxMap.Shared.Contracts.Enums;

namespace LuxMap.Modules.Telemetry.Entities;

/// <summary>
/// An IoT device in a main lighting cabinet (drift "BE-14 / IoT", I-1…I-6).
/// </summary>
/// <remarks>
/// <para>
/// There is NO device on individual poles (I-1): the only role left is
/// <see cref="NodeRole.SegmentController"/>, kept under that name so the front end does not change
/// (I-7). The device sits in a cabinet and reaches lamps through the feeders it switches —
/// <see cref="FeederControl"/> — never through a pole column.
/// </para>
/// <para>
/// <b>It has no location of its own since CAB-3.</b> The cabinet is the asset and carries the point; the
/// device is equipment mounted on it, fitted only where the commune asks for one. Reads take the point from
/// <c>electrical_cabinet.geom</c>.
/// </para>
/// <para>
/// <c>node_status</c> is NOT stored (I-3). It is derived on read from <see cref="LastReportAt"/> and
/// the <c>iot_offline_after_minutes</c> system setting (<see cref="NodeSilence"/>); a stored status would need a job to flip it to offline,
/// because a dead device cannot report its own death.
/// </para>
/// </remarks>
public class IotNode : ICommuneScoped
{
    /// <summary>Generated by the database sequence — never assign it when inserting.</summary>
    public string NodeId { get; set; } = null!;

    public required string CommuneId { get; set; }

    public NodeRole NodeRole { get; set; } = NodeRole.SegmentController;

    /// <summary>
    /// The cabinet the device is mounted in (CAB-3): REQUIRED, and at most one device per cabinet
    /// (<c>ux_iot_node_cabinet_id</c>). Same commune as the cabinet — composite foreign key.
    /// </summary>
    public required string CabinetId { get; set; }

    /// <summary>
    /// <c>true</c> only for the self-built testbed (D-R7): the team never operates a commune's grid,
    /// so a device in the field only measures and reports.
    /// </summary>
    public bool SupportsRemoteControl { get; set; }

    /// <summary>
    /// <c>calibration_rig</c> for the testbed hardware (I-5), <c>simulated</c> for demo rows. Never
    /// <c>field</c>: the team installs nothing in the field (D-R10).
    /// </summary>
    public DataSource DataSource { get; set; }

    /// <summary>
    /// SHA-256 (hex) of the device's secret (LIGHT-CTRL LC-2) — never the secret itself. <c>NULL</c> = no secret issued yet, so
    /// the device cannot authenticate. Set only through <c>POST /assets/iot-nodes/{id}/credential</c>.
    /// </summary>
    public string? CredentialHash { get; set; }

    /// <summary>When the current secret was issued; <c>NULL</c> exactly when <see cref="CredentialHash"/> is.</summary>
    public DateTime? CredentialSetAt { get; set; }

    /// <summary>Written by telemetry ingest (IOT-09). NULL means the device has never reported.</summary>
    public DateTime? LastReportAt { get; set; }

    /// <summary>
    /// The firmware the device last said it runs (BE-34 D-4) — a <c>node_firmware</c> row of <c>artifact_version</c>. NULL until a
    /// heartbeat names one. What it ran at an earlier moment is <see cref="IotNodeFirmware"/>, not this column.
    /// </summary>
    public long? FirmwareVersionId { get; set; }

    public DateTime CreatedAt { get; set; }

    public DateTime UpdatedAt { get; set; }
}

/// <summary>
/// One change of a device's firmware: from <see cref="FirstSeenAt"/> on, the device said it runs <see cref="FirmwareVersionId"/>
/// (BE-34 D-4). Append-only — "what did device X run at time T" is the newest row at or before T. Written only when the reported
/// firmware differs from <see cref="IotNode.FirmwareVersionId"/>, so a heartbeat every minute adds nothing.
/// </summary>
public sealed class IotNodeFirmware : ICommuneScoped, IImmutableRecord
{
    public long ChangeId { get; set; }

    public required string NodeId { get; set; }

    /// <summary>The device's commune, copied from it by the server.</summary>
    public required string CommuneId { get; set; }

    public long FirmwareVersionId { get; set; }

    public DateTime FirstSeenAt { get; set; }
}

